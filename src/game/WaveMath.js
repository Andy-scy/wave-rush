// 波浪数学 —— JS 与 GLSL 共用同一套公式（Ocean.js 顶点着色器内是同一份实现）
// 海面高度 = 域扭曲坐标下的【基础7向波 × 浪区增幅 × 涌浪团块 × 群波包络】+ 浪区陡峭短波 + 全局涟漪
// 所有函数保持纯函数（无内部状态、同输入同输出）。
// 浪区定位（zoneGauss / ampAt）一律用【原始世界坐标】，保证巨浪区位置不随扭曲漂移。
//
// ═══════ 波形常量表（必须与 Ocean.js VERT 顶部注释表逐常量一致，两处同步修改）═══════
//  域扭曲:   wx = x + sin(x*0.036 + z*0.027 + t*0.15) * 7.0
//            wz = z + sin(x*0.029 - z*0.032 - t*0.11) * 7.0
//  基础波 7 分量 (kx, kz, omega, amp)，含 2 个近反向传播浪系：
//            ( 0.052,  0.031,  0.90, 0.58)
//            ( 0.116, -0.087,  1.30, 0.21)
//            ( 0.148,  0.132,  1.72, 0.11)
//            ( 0.320, -0.270,  2.30, 0.055)
//            (-0.045, -0.031,  0.70, 0.34)   ← 近反向于第 1 分量
//            (-0.077,  0.070, -1.05, 0.17)   ← 近反向于第 2 分量
//            ( 0.036,  0.059,  0.51, 0.26)
//  涌浪团块:  1 + 0.35 * sin(x*0.011 + z*0.017 + t*0.045) * sin(x*0.019 - z*0.023 - t*0.031)
//  群波包络:  0.55 + 0.45 * sin(-(x*0.859 + z*0.512) * 0.055 - t*0.42)   （波长 ~114m，与主波系同向推进）
//  陡峭短波:  sin(w.x*0.14 + w.z*0.11 + t*1.6) * 1.7 * f
//             sin(w.x*0.23 - w.z*0.19 + t*2.4) * 0.55 * f    （f = zoneGauss，起飞核心，不许削弱）
//  全局涟漪:  sin(w.x*0.71 + w.z*0.64 + t*2.90) * 0.035
// ═════════════════════════════════════════════════════════════════════════════════

// 浪区高斯因子（0..1）：巨浪区 + 中浪区（原始世界坐标，起飞区位置固定）
export function zoneGauss(x, z) {
  let f = Math.exp(-((x - 90) * (x - 90) + (z - 400) * (z - 400)) / (150 * 150));
  f += Math.exp(-((x - 20) * (x - 20) + (z + 150) * (z + 150)) / (100 * 100)) * 0.55;
  return Math.min(f, 1);
}

// 位置处的浪区增幅倍数（基础波振幅）
export function ampAt(x, z) {
  let a = 1.0;
  a += 2.5 * Math.exp(-((x - 90) * (x - 90) + (z - 400) * (z - 400)) / (150 * 150));
  a += 1.55 * Math.exp(-((x - 20) * (x - 20) + (z + 150) * (z + 150)) / (100 * 100));
  return a;
}

// 基础波（未乘浪区增幅/团块调制；oceanHeight 传入域扭曲后的坐标 wx/wz）
export function baseWave(x, z, t) {
  let h = 0.0;
  h += Math.sin(x * 0.052 + z * 0.031 + t * 0.90) * 0.58;
  h += Math.sin(x * 0.116 - z * 0.087 + t * 1.30) * 0.21;
  h += Math.sin(x * 0.148 + z * 0.132 + t * 1.72) * 0.11;
  h += Math.sin(x * 0.32 - z * 0.27 + t * 2.30) * 0.055;
  h += Math.sin(-x * 0.045 - z * 0.031 + t * 0.70) * 0.34;
  h += Math.sin(-x * 0.077 + z * 0.070 - t * 1.05) * 0.17;
  h += Math.sin(x * 0.036 + z * 0.059 + t * 0.51) * 0.26;
  return h;
}

// 涌浪团块：双 sin 积调制局部振幅（±35%，patch 尺度约 150~310m，漂移周期 140~200s）
// 让远海出现"这片浪大、那片平"的随机团块
function swellMod(x, z, t) {
  return 1.0 + 0.35 * Math.sin(x * 0.011 + z * 0.017 + t * 0.045) * Math.sin(x * 0.019 - z * 0.023 - t * 0.031);
}

// 群波包络（wave sets）：与主波系 (0.052,0.031) 同向传播的慢波振幅包络
// 波长 2π/0.055 ≈ 114m，推进方向 -(0.859,0.512) 与主波一致 → 涌浪"一阵高一阵平"成组推进
// 取值 0.10~1.00（均值 0.55）。只调制基础涌浪，不作用于陡峭短波（起飞项不许削弱）
function waveSetEnv(x, z, t) {
  return 0.55 + 0.45 * Math.sin(-(x * 0.859 + z * 0.512) * 0.055 - t * 0.42);
}

// 完整海面高度（开销：15 次 sin + 4 次 exp，无分配；粒子系统每帧高频调用）
export function oceanHeight(x, z, t) {
  // 域扭曲：平滑慢漂移的坐标偏移场，打破各波系的方向规律对齐
  const wx = x + Math.sin(x * 0.036 + z * 0.027 + t * 0.15) * 7.0;
  const wz = z + Math.sin(x * 0.029 - z * 0.032 - t * 0.11) * 7.0;
  const f = zoneGauss(x, z);
  const h = baseWave(wx, wz, t) * ampAt(x, z) * swellMod(x, z, t) * waveSetEnv(x, z, t)
    // 浪区陡峭短波（可把高速摩托艇弹起，振幅/波数常量不许改）
    + Math.sin(wx * 0.14 + wz * 0.11 + t * 1.6) * 1.7 * f
    + Math.sin(wx * 0.23 - wz * 0.19 + t * 2.4) * 0.55 * f
    // 全局涟漪
    + Math.sin(wx * 0.71 + wz * 0.64 + t * 2.90) * 0.035;
  return h;
}

// 海面法线（有限差分，供摩托艇姿态用）
export function oceanNormal(x, z, t, out) {
  const e = 0.9;
  const hL = oceanHeight(x - e, z, t), hR = oceanHeight(x + e, z, t);
  const hD = oceanHeight(x, z - e, t), hU = oceanHeight(x, z + e, t);
  const nx = hL - hR, nz = hD - hU;
  const len = Math.hypot(nx, 2 * e, nz);
  out.x = nx / len; out.y = 2 * e / len; out.z = nz / len;
  return out;
}
